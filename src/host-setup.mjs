/** Pure setup helpers: validate machine options and render configuration before changing services. */
import { isIP } from 'node:net'

import { normalizeHostRouting } from './host-routing.mjs'

export function parseOptions(args, names, repeatable = []) {
  const options = {}
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index]
    const equals = argument.indexOf('=')
    const name = equals < 0 ? argument : argument.slice(0, equals)
    if (!names.includes(name)) throw new Error(`unknown option: ${name}`)
    const value = equals < 0 ? args[++index] : argument.slice(equals + 1)
    if (!value || value.startsWith('--')) throw new Error(`${name} requires a value`)
    if (repeatable.includes(name)) (options[name] ??= []).push(value)
    else options[name] = value
  }
  return options
}

export function bootstrapSettings(args, previous = {}) {
  const flags = {
    '--domain': 'domain',
    '--preferred-domain': 'preferredDomain',
    '--proxy-port': 'proxyPort',
    '--public-port': 'publicPort',
    '--public-scheme': 'publicScheme',
    '--proxy-network': 'proxyNetwork',
    '--proxy-bind-address': 'proxyBindAddress'
  }
  const options = parseOptions(args, [...Object.keys(flags), '--secondary-domain'], ['--secondary-domain'])
  const settings = { ...previous, enabled: true }
  for (const [flag, key] of Object.entries(flags)) {
    if (options[flag] !== undefined) {
      settings[key] = key.endsWith('Port') ? Number(options[flag]) : options[flag]
    }
  }
  if (options['--secondary-domain']) settings.secondaryDomains = options['--secondary-domain']
  return { ...settings, ...normalizeHostRouting(settings) }
}

export function traefikConfig(template, settings) {
  const config = normalizeHostRouting(settings)
  const host = config.proxyBindAddress.includes(':') ? `[${config.proxyBindAddress}]` : config.proxyBindAddress
  const address = config.proxyNetwork === 'host' ? `${host}:${config.proxyPort}` : ':80'
  return template.replace('address: ":80"', `address: ${JSON.stringify(address)}`)
}

function network(value) {
  const [address, prefix, ...extra] = value.split('/')
  const family = isIP(address)
  if (!family || extra.length || (prefix !== undefined
    && (!/^\d+$/.test(prefix) || Number(prefix) > (family === 4 ? 32 : 128)))) {
    throw new Error(`invalid allowed IP address or CIDR: ${value}`)
  }
  return value
}

function nginxPath(value) {
  if (typeof value !== 'string' || !value.startsWith('/') || /[\n\r\0$]/.test(value)) {
    throw new Error('certificate paths must be absolute paths without nginx variables')
  }
  return JSON.stringify(value)
}

export function nginxConfig(settings, args = []) {
  const config = normalizeHostRouting(settings)
  const options = parseOptions(args, ['--upstream', '--allow', '--ssl-certificate', '--ssl-certificate-key'], ['--allow'])
  const address = config.proxyBindAddress.includes(':') ? `[${config.proxyBindAddress}]` : config.proxyBindAddress
  const upstream = new URL(options['--upstream'] ?? `http://${address}:${config.proxyPort}`)
  if (upstream.protocol !== 'http:' || upstream.username || upstream.password || upstream.pathname !== '/'
    || upstream.search || upstream.hash || /[\s;{}$"\\]/.test(upstream.host)) {
    throw new Error('--upstream must be an HTTP origin without credentials, a path, or query parameters')
  }
  const allow = [...new Set(['127.0.0.1', '::1', ...(options['--allow'] ?? [])])].map(network)
  let tls = ''
  if (config.publicScheme === 'https') {
    if (!options['--ssl-certificate'] || !options['--ssl-certificate-key']) {
      throw new Error('HTTPS requires --ssl-certificate and --ssl-certificate-key (paths inside nginx)')
    }
    tls = `\n    ssl_certificate ${nginxPath(options['--ssl-certificate'])};\n    ssl_certificate_key ${nginxPath(options['--ssl-certificate-key'])};\n`
  }
  return `# Generated by devkit nginx. Include inside nginx's http context.
# Exact server_name entries keep precedence over these wildcard routes.
map $http_upgrade $devkit_connection_upgrade {
    default upgrade;
    "" close;
}

server {
    listen ${config.publicPort}${config.publicScheme === 'https' ? ' ssl' : ''};
    server_name ${[config.domain, ...config.secondaryDomains].map((domain) => `*.${domain}`).join(' ')};
${tls}
${allow.map((entry) => `    allow ${entry};`).join('\n')}
    deny all;

    location / {
        proxy_pass ${upstream.origin};
        proxy_http_version 1.1;
        proxy_set_header Host $http_host;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $devkit_connection_upgrade;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_buffering off;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
    }
}
`
}
